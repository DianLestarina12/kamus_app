<h3> <em>Kruna Alus Sor</em> (ASO)</h3>
    
    <p>
        <em>Kruna alus sor</em> adalah kata-kata yang mempunyai nilai rasa halus atau menghormat, dipakai merendahkan diri atau merendahkan orang lain yang status sosialnya lebih rendah. Jadinya, yang akan berbahasa <em>alus sor</em> dalam pergaulan, semua masyarakat Bali yang mengangap diri mempunyai status soaial lebih rendah dalam berbicara. Yang tercetak tebal di bawah, contoh <em>kruna alus sor</em>.
    </p>

    <ol>
        <li>
            Jantos jebos titiang jagi <strong>mabanyu</strong> riin! <br>
            'Tunggu sebentar saya akan kencing dulu'
        </li>
        <li>
            Banggayang Ratu, titiang jagi <strong>néwék tangkil</strong> ka geria! <br>
            'Biarkan Ratu, saya akan sendirian menghadap ke geria'
        </li>
        <li>
            Titiang <strong>mawasta</strong> I Wayan Mudara. <br>
            'Saya bernama I Wayan Mudara'
        </li>
        <li>
            Ipun sampun dumunan <strong>padem</strong>. <br>
            'Ia sudah duluan meninggal'
        </li>
    </ol>

    <p>
        Jadi, berdasarkan contoh kalimat di atas, yang termasuk <em>kruna alus sor</em> antara lain: <em>mabanyu</em> 'kencing', <em>newek</em> 'sendiri', <em>tangkil</em> 'menghadap', <em>mawasta</em> 'bernama', <em>neda</em> 'makan', <em>padem</em> 'meninggal'. Contoh lainnya: <em>manah</em> 'pikiran', <em>sengkaon</em> 'sakit', <em>antuk</em> 'oleh', <em>matur</em> 'berbicara', <em>muat</em> 'membawa', dan lain-lain.
    </p>

