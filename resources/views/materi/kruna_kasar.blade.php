    <h3><em>Kruna Kasar</em></h3>
    
    <p>
        <em>Kruna kasar</em> yaitu kata bahasa Bali yang rasa bahasannya jelek (<em>kaon</em>). Kata-kata kasar dipakai untuk membentuk komunikasi kasar. Itulah sebabnya kata-kata <em>kasar</em> biasa dipakai berbicara pada saat marah, saat bertengkar atau mencaci-maki. Dalam berkomunikasi, kata-kata <em>kasar</em> sebagai unsur utama dalam membentuk <em>kalimat kasar</em>, sebagai dasar pula dalam membentuk <em>basa kasar</em>[cite: 26].<br>
        Contoh <em>kruna kasar</em>, yang bercetak tebal dan miring di bawah ini[cite: 26].
    </p>

