    <h3><em>Kruna Andap</em></h3>
    
    <p>
        Pada mulanya, <em>kruna andap</em> ini disebut <em>kruna lepas hormat</em> atau <em>kruna kapara</em>. <em>Kruna andap</em> adalah kata-kata yang nilai rasanya biasa, lepas hormat atau <em>andap</em> (rendah), tidak halus dan tidak kasar. Kata-kata tersebutlah yang membentuk kalimat-kalimat <em>andap</em>. Dipakai berbicara oleh orang-orang yang berkasta sama atau sama status atau kelahirannya. Selain itu, kata-kata <em>andap</em> tersebut setelah membentuk kalimat, bisa dipakai berbicara oleh <em>sang singgih</em> (golongan terhormat) terhadap <em>sang sor</em> (golongan penghormat).
    </p>

    <p>
        Bentuk kata yang tergolong <em>kruna andap</em> tersebut mirip dengan <em>kruna mider</em>. Perbedaannya, kalau <em>kruna mider</em> sama sekali tidak memiliki bentuk halus, tetapi <em>kruna andap</em> pasti mempunyai bentuk halus. Umpama <em>kruna</em> "<strong>kija</strong>" (<em>mider</em>) tidak ada bentuk halusnya. Berbeda dengan <em>kruna</em> "<strong>kaja</strong>" (<em>andap</em>), mempunyai bentuk halus <strong>kalér</strong>.
    </p>

    <p>
        Kata <strong>kija</strong> bisa digunakan dalam berbahasa <em>andap</em>, bisa juga digunakan dalam berbahasa <em>alus singgih</em>, bisa digunakan dalam berbahasa <em>alus sor</em>, bisa juga digunakan dalam berbahasa yang <em>kasar</em>. Perhatikan contoh berikut ini!
    </p>

    <ol start="6">
        <li>
            <em>Ratu jagi lunga</em> <strong>kija</strong>?<br>
            'Ratu akan pergi ke mana?'
        </li>
        <li>
            <em>Bapak lakar</em> <strong>kija</strong>?<br>
            'Ayah akan ke mana?
        </li>
        <li>
            <em>Ia</em> <strong>kija</strong> <em>kadén Luh Rai tusang maorahan?</em><br>
            'Entah ke mana Luh Rai tidak memberitahukan?'.
        </li>
    </ol>

    <p>
        Berbeda dengan kata <strong>kaja</strong> (<em>andap</em>), oleh karena ia mempunyai bentuk halus <strong>kalér</strong>. Kata <em>andap</em> <strong>kaja</strong> hanya dipakai berbicara <em>andap</em> atau <em>kasar</em>, sedangkan kata <strong>kalér</strong> (<em>AMI</em>) hanya boleh digunakan dalam bahasa <em>alus</em>. Contohnya:
    </p>

    <ol>
        <li>
            <em>Simané dini malénan ajak jumah kaja.</em><br>
            'Tradisi di sini berbeda dengan di rumah utara'
        </li>
        <li>
            <em>Sapunapi mangkin simakramané kaler, Ratu?</em><br>
            Bagaimana sekarang tatakrama di utara, Ratu?'
        </li>
        <li>
            <em>Bapa teka uli kaja busan dini.</em><br>
            'Bapak datang dari utara tadi di sini'
        </li>
    </ol>

    <p>
        Contoh <em>Kruna Andap</em> lainnya: jemak 'ambil', duur 'atas', milu 'ikut', kema 'ke sana', lakar 'akan', ngae 'membuat', adan 'nama', dan sebagainya seperti pada contoh di bawah ini.
    </p>

    <ol>
        <li>
            <strong>Luh, jemakang bapa rokoné</strong> <em>di</em> <strong>duur mejané!</strong><br>
            'Luh, ambilkan ayah rokok di atas mejanya!'
        </li>
        <li>
            <strong>Kéngkén, Cai lakar milu kema?</strong><br>
            'Bagaimana, Kamu akan ikut ke sana?'
        </li>
        <li>
