    <h3><em>Kruna Alus Singgih</em> (ASI)</h3>
    
    <p>
        Kata-kata alus yang dipakai menghormati orang yang patut dihormati disebut <em>kruna alus singgih</em>. Perbedaannya dengan <em>kruna Ami</em>, bahwasanya <em>Kruna ASI</em> pasti mempunyai bentuk <em>andap</em>, juga mempunyai bentuk <em>alus sor (Aso)</em>. Umpama <em>kruna ASI</em> <strong>marayunan</strong> (makan), mempunyai wangun <em>Andap</em> <strong>madaar</strong> (makan), juga mempunyai bentuk <em>alus sor</em> <strong>ngajeng</strong> atau <strong>nunas</strong> (makan). Kata-kata yang tercetak tebal atau miring, di bawah semuanya contoh <em>kruna alus singgih</em>.
    </p>

