    <h3><em>Kruna Alus Mider</em> (AMI)</h3>
    
    <p>
        <em>Kruna alus mider</em> adalah kata bahasa Bali yang mempunyai nilai rasa halus, dan mempunyai dua fungsi, bisa dipakai menghormat (<em>nyinggihang sang singgih</em>) dan juga dipakai merendahkan golongan bawah (<em>ngesorang sang sor</em>). 
        Selain itu, <em>kruna alus mider</em> pasti mempunyai bentuk biasa (<em>andap</em>) (Suasta, 1997: 26). 
        Kata-kata yang tercetak tebal di bawah, sebagai contoh <em>kruna alus mider</em> (Ami).
    </p>

    <ol>
        <li>
            <em>Ida Cokorda</em> <strong>sampun rauh saking Jawi</strong>. (Asi) <br>
            'Ida Cokorda sudah datang dari Jawa'
        </li>
        <li>
            <em>Bapak titiang</em> <strong>sampun rauh saking Jawi</strong>.(Aso) <br>
            'Bapak saya sudah datang dari Jawa'
        </li>
    </ol>

    <p>
        Di dalam kalimat (1) dan (2) di atas, sudah pasti ada empat kata/<em>kruna</em> yang mempunyai nilai rasa <em>alus mider</em> yaitu: 
        <em>kruna</em> <strong>sampun</strong>, <em>kruna</em> <strong>rauh</strong>, <em>kruna</em> <strong>saking</strong>, dan <em>kruna</em> <strong>Jawi</strong>. 
        Yang menyebabkan keempat kata tersebut disebut <em>kruna alus mider</em> karena dipakai di dalam kalimat <em>Asi</em> (seperti pada kalimat no.1), juga dapat dipakai dalam kalimat <em>Aso</em> (seperti pada no. 2). Di samping itu, keempat kata <em>Ami</em> tersebut mempunyai bentuk <em>andap</em>. Kata <strong>rauh</strong> <em>andapnya</em> <strong>teka</strong>; kata <strong>sampun</strong> <em>andapnya</em> <strong>suba</strong>, kata <strong>saking</strong> <em>andapnya</em> <strong>uli</strong>; dan kata <strong>Jawi</strong> <em>andapnya</em> <strong>Jawa</strong>. Hal itulah yang menyebabkan keempat kata tersebut termasuk kata atau <em>kruna alus mider</em>. Contoh <em>kruna alus mider</em> lainnya: <em>uning</em> 'tahu', <em>lali</em> 'lupa', <em>eling</em> "ingat", <em>sampun</em> 'sudah', <em>ngambil</em> 'mengambil'.
    </p>

    <p>Contoh <em>kruna alus mider</em> (Ami) berbentuk kalimat:</p>
    <ol>
        <li>
            <em>Ampura ping banget, titiang nénten</em> <strong>uning</strong>. <em>Ratu</em> <strong>uning</strong>? <br>
            'Maaf yang besar, saya tidak tahu. Ratu tahu?'
        </li>
        <li>
            <em>Ratu pasti</em> <strong>lali</strong> <em>ring titiang nggih? Titiang nénten lali.</em> <br>
            'Ratu pasti lupa pada saya ya? Saya tidak lupa'
        </li>
        <li>
            <em>Titiang kantun</em> <strong>éling</strong> <em>ring Ratu. Rabin Iratuné kantun taler</em> <strong>éling</strong> <em>taler ring titiang.</em> <br>
            'Saya masih ingat pada Ratu. Isteri Ratu masih juga ingat pada saya'
        </li>
        <li>
            <em>Ratu, icén ja titiang</em> <strong>nyelang</strong> <em>HP druené! Ratu durus jagi</em> <strong>nyelang</strong> <em>jinah?</em> <br>
            'Ratu, tolong berikan saya meminjam HP, Ratu jadi mau meminjam uang?'
        </li>
    </ol>

    <p>
        Di dalam kalimat (1) di atas, terlihat jelas ada empat kata yang termasuk tingkatan kata <em>alus mider</em> yaitu:
    </p>
    
    <div class="row mb-3 ps-3">
        <div class="col-sm-6">
            - kruna <strong>sampun</strong>,<br>
            - kruna <strong>saking</strong>
        </div>
        <div class="col-sm-6">
            - kruna <strong>rauh</strong>,<br>
            - kruna <strong>Jawi</strong>.
        </div>
    </div>

    <p>
        Yang menyebabkan keempat kata tersebut disebut <em>kruna alus mider</em> karena dapat dipakai pada kalimat <em>Alus singgih</em> (seperti pada kalimat 1), juga dipakai pada kalimat <em>Alus sor</em> (seperti kalimat 2).
    </p>

    <p>
        Selain itu, keempat <em>kruna Ami</em> tersebut memiliki bentuk <em>andap</em>. Kata <strong>rauh</strong> 'datang' bentuk <em>andapnya</em> <strong>teka</strong>; kata <strong>sampun</strong> 'sudah' bentuk <em>andapnya</em> <strong>suba</strong>, kata <strong>saking</strong> 'dari' bentuk <em>andapnya</em> <strong>uli</strong>; dan kata <strong>Jawi</strong> bentuk <em>andapnya</em> <strong>Jawa</strong>. Itu pulalah yang menyebabkan keempat kata tersebut termasuk <em>kruna alus mider</em>.
    </p>

    <p>
        Demikian pula halnya kata-kata <strong>nénten, uning, ring, wénten,</strong> dan <strong>karya</strong>. Semuanya ini termasuk kata-kata <strong>alus mider</strong> karena dapat digunakan ketika berbicara menghormat maupun ketika berbicara merendahkan diri seseorang.
    </p>

    <p>Sebagai contoh:</p>
    <ol>
        <li>
            Ida <strong>nénten</strong> <em>sareng</em>, titiang <strong>nénten</strong> <em>sareng</em>, dané <strong>nénten</strong> <em>sareng</em>, ipun <strong>nénten</strong> <em>sareng</em>, Luh Rai <strong>nénten</strong> <em>sareng</em>, Gusti Ayu <strong>nénten</strong> <em>sareng</em>, Ida Bagus Aji taler <strong>nénten</strong> <em>sareng</em>. (Semuanya benar).<br>
            'Beliau tidak ikut, saya tidak ikut, beliau tidak ikut, dia tidak ikut, Luh Rai tidak ikut, Gusti Ayu tidak ikut, Ida Bagus Aji juga tidak ikut'.
        </li>
        <li>
            Dané <strong>sampun makarya</strong>, ida <strong>sampun makarya</strong>, ipun <strong>sampun makarya</strong>, Madé Lara <strong>sampun makarya</strong>, Mekelé istri <strong>sampun makarya</strong>, Nang Klencéng pun <strong>sampun makarya</strong>. (Semuanya juga benar).<br>
            'Beliau sudah bekerja, beliau sudah bekerja, dia sudah bekerja, Made Lara sudah bekerja, Mekel perempuan sudah bekerja, Nang Klenceng juga sudah bekerja'.
        </li>
    </ol>

    <p>
        Jadi di sini kelihatan bahwa sebuah kata yang termasuk jenis alus mider dapat digunakan dalam berbagai tataran dalam bahasa alus, baik untuk menyebut keadaan orang golongan atas maupun orang golongan bawah.
    </p>

