    <h3><em>Kruna Mider</em></h3>
    
    <p>
        Pengertian <em>kruna mider</em> kalau dibandingkan dengan <em>kruna alus mider</em> (AMI) sering menimbulkan pemikiran yang membingungkan. Yang menyebabkan demikian, karena baik <em>kruna mider</em> maupun <em>kruna alus mider</em>, bisa dipakai menghormati (<em>nyinggihang</em>), juga bisa dipakai merendahkan (<em>ngasorang</em>) Perbedaannya, <em>kruna alus mider</em> mempunyai bentuk <em>andap</em>, sementara <em>kruna mider</em> sama sekali tidak mempunyai bentuk lain.
    </p>

    <p>
        Jadi, <em>kruna mider</em> adalah kata bahasa Bali yang mempunyai bentuk hanya satu, tidak mempunyai bentuk <em>alus singgih</em>, <em>alus sor</em>, atau <em>alus mider</em>, serta tidak mempunyai bentuk lainnya, sehingga boleh kemana-mana (<em>maideran</em>) di dalam percakapan. Perhatikan contoh di bawah!
    </p>

